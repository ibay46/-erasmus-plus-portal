"use client";

import { useState } from "react";
import { KA_ACTION_LABELS, EDUCATION_SECTOR_LABELS, KA_ACTION_SECTORS } from "@/lib/content/kaActions";
import type { Locale } from "@/lib/i18n/locale";

const ORG_TYPES = ["Okul", "STK / Dernek-Vakıf", "Belediye", "Üniversite", "Meslek Eğitimi Kurumu", "Diğer"];
const ORG_TYPES_EN = ["School", "NGO / Association-Foundation", "Municipality", "University", "Vocational Training Institution", "Other"];

const KA_ACTION_LABELS_EN: Record<string, string> = {
  KA210: "KA210 — Small-scale Partnerships",
  KA220: "KA220 — Cooperation Partnerships",
  KA240: "KA240 — Simplified Partnerships",
};

const EDUCATION_SECTOR_LABELS_EN: Record<string, string> = {
  SCH: "School Education",
  VET: "Vocational Education and Training",
  ADU: "Adult Education",
  YOU: "Youth",
  HED: "Higher Education",
};

const STRINGS = {
  tr: {
    orgTypeLabel: "Kuruluş Tipi",
    kaActionLabel: "KA Eylemi",
    sectorLabel: "Sektör",
    themeLabel: "İlgi Alanı / Tema",
    themePlaceholder: "örn. dijital beceriler ve medya okuryazarlığı",
    generating: "Üretiliyor…",
    generate: "Proje Fikri Üret",
    remainingToday: (n: number) => `Bugün kalan ücretsiz kullanım hakkınız: ${n}`,
    themeRequired: "Lütfen proje temanızı/ilgi alanınızı yazın.",
    genericError: "Bir hata oluştu. Lütfen tekrar deneyin.",
    connectionError: "Bağlantı hatası. Lütfen tekrar deneyin.",
    draftLabel: "Proje Fikri Taslağı",
    targetGroupLabel: "Hedef Grup",
    objectivesLabel: "Amaçlar",
    sampleActivitiesLabel: "Örnek Faaliyetler",
    addressedPrioritiesLabel: "Hitap Ettiği Öncelikler",
    disclaimer:
      "Bu taslak yapay zeka tarafından üretilmiştir; başlangıç noktası olarak kullanın. Başvurudan önce kendi kurumunuzun bağlamına göre yeniden yazın, somut ortaklar ve rakamlarla destekleyin.",
    orgTypes: ORG_TYPES,
    kaActionLabels: KA_ACTION_LABELS,
    sectorLabels: EDUCATION_SECTOR_LABELS,
  },
  en: {
    orgTypeLabel: "Organisation Type",
    kaActionLabel: "KA Action",
    sectorLabel: "Sector",
    themeLabel: "Area of Interest / Theme",
    themePlaceholder: "e.g. digital skills and media literacy",
    generating: "Generating…",
    generate: "Generate Project Idea",
    remainingToday: (n: number) => `Your remaining free uses today: ${n}`,
    themeRequired: "Please enter your project theme / area of interest.",
    genericError: "An error occurred. Please try again.",
    connectionError: "Connection error. Please try again.",
    draftLabel: "Project Idea Draft",
    targetGroupLabel: "Target Group",
    objectivesLabel: "Objectives",
    sampleActivitiesLabel: "Sample Activities",
    addressedPrioritiesLabel: "Addressed Priorities",
    disclaimer:
      "This draft was generated by AI; use it as a starting point. Before applying, be sure to rewrite it to fit your own organisation's context and support it with concrete partners and figures.",
    orgTypes: ORG_TYPES_EN,
    kaActionLabels: KA_ACTION_LABELS_EN,
    sectorLabels: EDUCATION_SECTOR_LABELS_EN,
  },
};

interface GeneratedIdea {
  title: string;
  summary: string;
  targetGroup: string;
  objectives: string[];
  sampleActivities: string[];
  addressedPriorities: string[];
}

export function ProjectIdeaGenerator({ locale = "tr" }: { locale?: Locale } = {}) {
  const t = STRINGS[locale];
  const ORG_TYPES_LOCALIZED = t.orgTypes;
  const [orgType, setOrgType] = useState(ORG_TYPES_LOCALIZED[0]);
  const [kaAction, setKaAction] = useState("KA210");
  const [sector, setSector] = useState(KA_ACTION_SECTORS["KA210"][0]);
  const [theme, setTheme] = useState("");

  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [idea, setIdea] = useState<GeneratedIdea | null>(null);
  const [remaining, setRemaining] = useState<number | null>(null);

  const availableSectors = KA_ACTION_SECTORS[kaAction] ?? [];

  function handleKaActionChange(next: string) {
    setKaAction(next);
    const sectors = KA_ACTION_SECTORS[next] ?? [];
    if (!sectors.includes(sector)) setSector(sectors[0]);
  }

  async function handleSubmit(e: React.FormEvent) {
    e.preventDefault();
    if (!theme.trim()) {
      setError(t.themeRequired);
      return;
    }
    setLoading(true);
    setError(null);
    setIdea(null);

    try {
      const res = await fetch("/api/proje-fikri-uretici", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ orgType, sector, kaAction, theme: theme.trim() }),
      });
      const data = await res.json();
      if (!res.ok) {
        setError(data.error ?? t.genericError);
        return;
      }
      setIdea(data.idea);
      setRemaining(data.remainingToday);
    } catch {
      setError(t.connectionError);
    } finally {
      setLoading(false);
    }
  }

  return (
    <div className="space-y-6">
      <form onSubmit={handleSubmit} className="space-y-4 rounded-xl border border-border bg-card p-5">
        <div className="grid gap-4 sm:grid-cols-2">
          <label className="block">
            <span className="mb-1.5 block text-xs font-semibold uppercase tracking-wide text-muted-foreground">
              {t.orgTypeLabel}
            </span>
            <select
              value={orgType}
              onChange={(e) => setOrgType(e.target.value)}
              className="w-full cursor-pointer rounded-md border border-border bg-background px-3 py-2 text-sm text-foreground"
            >
              {ORG_TYPES_LOCALIZED.map((o) => (
                <option key={o} value={o}>
                  {o}
                </option>
              ))}
            </select>
          </label>

          <label className="block">
            <span className="mb-1.5 block text-xs font-semibold uppercase tracking-wide text-muted-foreground">
              {t.kaActionLabel}
            </span>
            <select
              value={kaAction}
              onChange={(e) => handleKaActionChange(e.target.value)}
              className="w-full cursor-pointer rounded-md border border-border bg-background px-3 py-2 text-sm text-foreground"
            >
              {Object.keys(KA_ACTION_LABELS).map((code) => (
                <option key={code} value={code}>
                  {t.kaActionLabels[code]}
                </option>
              ))}
            </select>
          </label>

          <label className="block">
            <span className="mb-1.5 block text-xs font-semibold uppercase tracking-wide text-muted-foreground">
              {t.sectorLabel}
            </span>
            <select
              value={sector}
              onChange={(e) => setSector(e.target.value)}
              className="w-full cursor-pointer rounded-md border border-border bg-background px-3 py-2 text-sm text-foreground"
            >
              {availableSectors.map((s) => (
                <option key={s} value={s}>
                  {t.sectorLabels[s] ?? s}
                </option>
              ))}
            </select>
          </label>

          <label className="block sm:col-span-2">
            <span className="mb-1.5 block text-xs font-semibold uppercase tracking-wide text-muted-foreground">
              {t.themeLabel}
            </span>
            <input
              type="text"
              value={theme}
              onChange={(e) => setTheme(e.target.value)}
              placeholder={t.themePlaceholder}
              maxLength={300}
              className="w-full rounded-md border border-border bg-background px-3 py-2 text-sm text-foreground placeholder:text-muted-foreground/60"
            />
          </label>
        </div>

        <button
          type="submit"
          disabled={loading}
          className="cursor-pointer inline-flex items-center rounded-lg bg-accent px-5 py-2.5 text-sm font-semibold text-accent-foreground transition-colors duration-200 hover:bg-accent/90 disabled:cursor-not-allowed disabled:opacity-60"
        >
          {loading ? t.generating : t.generate}
        </button>

        {remaining !== null && !error && (
          <p className="text-xs text-muted-foreground">{t.remainingToday(remaining)}</p>
        )}
      </form>

      {error && (
        <div className="rounded-lg border border-red-200 bg-red-50 px-4 py-3 text-sm text-red-700 dark:border-red-800 dark:bg-red-950/40 dark:text-red-300">
          {error}
        </div>
      )}

      {idea && (
        <div className="space-y-4 rounded-xl border border-accent/30 bg-accent/5 p-5">
          <div>
            <span className="text-xs font-semibold uppercase tracking-wide text-accent">{t.draftLabel}</span>
            <h3 className="mt-1 text-xl font-semibold text-foreground">{idea.title}</h3>
            <p className="mt-2 text-sm text-muted-foreground">{idea.summary}</p>
          </div>

          <div>
            <p className="text-xs font-semibold uppercase tracking-wide text-muted-foreground">{t.targetGroupLabel}</p>
            <p className="mt-1 text-sm text-foreground">{idea.targetGroup}</p>
          </div>

          <div>
            <p className="mb-1.5 text-xs font-semibold uppercase tracking-wide text-muted-foreground">{t.objectivesLabel}</p>
            <ul className="list-disc space-y-1 pl-5 text-sm text-foreground">
              {idea.objectives.map((o, i) => (
                <li key={i}>{o}</li>
              ))}
            </ul>
          </div>

          <div>
            <p className="mb-1.5 text-xs font-semibold uppercase tracking-wide text-muted-foreground">
              {t.sampleActivitiesLabel}
            </p>
            <ul className="list-disc space-y-1 pl-5 text-sm text-foreground">
              {idea.sampleActivities.map((a, i) => (
                <li key={i}>{a}</li>
              ))}
            </ul>
          </div>

          <div>
            <p className="mb-1.5 text-xs font-semibold uppercase tracking-wide text-muted-foreground">
              {t.addressedPrioritiesLabel}
            </p>
            <div className="flex flex-wrap gap-1.5">
              {idea.addressedPriorities.map((p, i) => (
                <span
                  key={i}
                  className="rounded-full border border-accent/30 bg-accent/10 px-2.5 py-1 text-xs font-medium text-accent"
                >
                  {p}
                </span>
              ))}
            </div>
          </div>

          <p className="border-t border-accent/20 pt-3 text-xs text-muted-foreground">
            {t.disclaimer}
          </p>
        </div>
      )}
    </div>
  );
}
